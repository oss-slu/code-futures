"""Every sentence a report can contain.

# Why this file exists

Reports are rendered from templates rather than generated by a language model,
and the whole register of the document follows from that.

Four reasons, and the first decides it. These are team-facing documents and a
false statement in one is something a team has to argue with; a template is
reviewed once and then correct for every repository, where generated prose has
to be read once per repository. Second, reports must be comparable side by
side, and two reports wording the same finding differently are not. Third, the
CI path runs on a GitHub runner with no model access, no key and no network
budget. Fourth, the same snapshot produces the same bytes, so a report can be
regenerated and diffed against its own past -- which is the continuous
improvement story the guidebook is built around.

The cost is that every sentence has to survive being written in advance, for a
repository nobody has looked at. That is a real constraint on how much a report
can say, and it is the right trade.

# Editing rules

- A template renders into a document somebody reads about their own work.
  Findings are next steps, absences are opportunities, and nothing here ranks
  anybody against anybody.
- Say what is true rather than what is not. "Tests that assert nothing still
  count toward coverage" lands where "coverage is not a measure of quality"
  reads as an apology.
- Short sentences. Where a sentence needs three commas, it is two sentences.
- Never phrase an `unreadable` finding so it could be read as the repository's
  fault. That outcome is about us.
- Changing wording here changes twenty-nine documents. That is the point.
"""

